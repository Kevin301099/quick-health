/*
  TEMPLATE. Replace the request and response mapping with the partner's documented API before going live.
  Everything partner-specific is in `toPartner` and `fromPartner`; the rest of the app does not change.
*/
function partnerHttpProvider(c: Config): FilingProvider {
  const base = c.PARTNER_API_URL.replace(/\/$/, '');
  const headers = { authorization: `Bearer ${c.PARTNER_API_KEY}`, 'content-type': 'application/json' };
  const toPartner = (p: FilingPacket) => ({
    external_reference: p.applicationId,
    visa_type: p.visa.days === 60 ? 'TOURIST_60_SINGLE' : 'TOURIST_30_SINGLE',
    applicant: {
      first_name: p.traveller.given,
      last_name: p.traveller.surname,
      gender: p.traveller.sex,
      date_of_birth: p.traveller.dob,
      nationality: p.traveller.nationality,
      place_of_birth: p.traveller.birthplace,
      passport_number: p.traveller.passportNo,
      passport_issue_date: p.traveller.passportIssued,
      passport_expiry_date: p.traveller.passportExpires,
      email: p.traveller.email,
      mobile: p.traveller.phone,
      profession: p.traveller.profession,
    },
    travel: { arrival_date: p.trip.arrival, departure_date: p.trip.departure, emirate: p.trip.emirate },
    documents: p.documents.map((d) => ({ type: d.slot.toUpperCase(), url: d.url, content_type: d.mime })),
  });
  const fromPartner = (r: { status?: string; message?: string; visa_number?: string; visa_url?: string; valid_until?: string }): FilingUpdate => {
    const map: Record<string, FilingState> = { RECEIVED: 'submitted', IN_PROCESS: 'processing', ACTION_REQUIRED: 'needs_info', APPROVED: 'approved', REJECTED: 'rejected' };
    const state = map[(r.status ?? '').toUpperCase()] ?? 'processing';
    return { state, message: r.message, permit: state === 'approved' && r.visa_number ? { number: r.visa_number, url: r.visa_url, validUntil: r.valid_until } : undefined };
  };
  return {
    name: 'partner_http',
    automatic: true,
    async submit(p) {
      // The idempotency key lets the partner ignore a repeat if we retry after a timeout. The short timeout keeps
      // filing inside the payment webhook's window; a slow partner is simply retried by the scheduled run.
      const r = await fetch(`${base}/applications`, { method: 'POST', headers: { ...headers, 'idempotency-key': p.applicationId }, body: JSON.stringify(toPartner(p)), signal: AbortSignal.timeout(15_000) });
      if (!r.ok) throw new Error(`Partner rejected the submission: ${r.status} ${await r.text()}`);
      const body = (await r.json()) as { reference: string; status?: string; message?: string };
      return { ref: body.reference, update: fromPartner(body) };
    },
    async poll(ref) {
      const r = await fetch(`${base}/applications/${encodeURIComponent(ref)}`, { headers, signal: AbortSignal.timeout(20_000) });
      if (!r.ok) throw new Error(`Partner status failed: ${r.status}`);
      return fromPartner(await r.json());
    },
  };
}
